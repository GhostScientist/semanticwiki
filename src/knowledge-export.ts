/** Open Knowledge Format v0.2 export. The human wiki is never rewritten. */
import * as fs from 'node:fs';
import * as path from 'node:path';
import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
import matter from 'gray-matter';
import { marked, type Token } from 'marked';
import { simpleGit } from 'simple-git';
import { documentSummary, extractHeadings, loadWikiCatalog, resolveWikiLink, type WikiDocument } from './wiki-catalog.js';

export const OKF_VERSION = '0.2';
export const KNOWLEDGE_DIRECTORY = 'knowledge';
const MARKER = '.semanticwiki-knowledge.json';
const DISCOVERY_MARKER = '<!-- Generated by SemanticWiki. -->';
const version = createRequire(import.meta.url)('../package.json').version as string;

export interface KnowledgeExportOptions {
  wikiDir: string;
  title?: string;
  repoPath?: string;
  sourceRepo?: string;
  sourceCommit?: string;
}

export interface KnowledgeExportResult {
  bundlePath: string;
  pageCount: number;
  manifestPath: string;
  discoveryWritten: boolean;
}

function encodePath(value: string): string {
  return value.split('/').map(encodeURIComponent).join('/');
}

function markdownLabel(value: string): string {
  return value.replace(/[\r\n]+/g, ' ').replace(/[\\[\]]/g, '\\$&');
}

function safeRelativePath(value: unknown): value is string {
  return typeof value === 'string' && value.length > 0 && !value.includes('\\') && !value.includes('\0') && !path.posix.isAbsolute(value) && value.split('/').every(part => part !== '..' && part !== '.' && part.length > 0);
}

function lstatIfPresent(value: string): fs.Stats | undefined {
  try { return fs.lstatSync(value); } catch (error) {
    if ((error as NodeJS.ErrnoException).code === 'ENOENT') return undefined;
    throw error;
  }
}

function assertRegularDestination(root: string, relative: string): void {
  if (!safeRelativePath(relative)) throw new Error(`Invalid managed knowledge path: ${relative}`);
  let current = root;
  for (const part of relative.split('/')) {
    current = path.join(current, part);
    if (lstatIfPresent(current)?.isSymbolicLink()) {
      throw new Error(`Refusing to write through a symbolic link: ${current}`);
    }
  }
}

/** Preserve prose and fenced examples; only actual Markdown link tokens are rewritten. */
function rewriteMarkdownLinks(body: string, rewrite: (href: string) => string): string {
  const rewriteToken = (token: Token): string => {
    if (token.type === 'code' || token.type === 'codespan' || token.type === 'html') return token.raw;
    if (token.type === 'link' || token.type === 'image') {
      const href = rewrite(token.href);
      const label = 'tokens' in token && Array.isArray(token.tokens) ? replaceChildren(token.text, token.tokens) : token.text;
      if (href === token.href && label === token.text) return token.raw;
      const title = token.title ? ` "${token.title.replace(/"/g, '&quot;')}"` : '';
      return `${token.type === 'image' ? '!' : ''}[${label}](<${href}>${title})`;
    }
    let children: Token[] = [];
    if ('tokens' in token && Array.isArray(token.tokens)) children = token.tokens;
    else if (token.type === 'list') children = token.items as Token[];
    else if (token.type === 'table') children = [...token.header, ...token.rows.flat()].flatMap(cell => cell.tokens);
    return replaceChildren(token.raw, children);
  };
  const replaceChildren = (raw: string, children: Token[]): string => {
    let result = '';
    let cursor = 0;
    for (const child of children) {
      const start = raw.indexOf(child.raw, cursor);
      if (start < 0) continue;
      result += raw.slice(cursor, start) + rewriteToken(child);
      cursor = start + child.raw.length;
    }
    return result + raw.slice(cursor);
  };
  return replaceChildren(body, marked.lexer(body));
}

function publicRepositoryUrl(value?: string): string | undefined {
  if (!value) return undefined;
  const ssh = value.match(/^git@([a-z\d.-]+):([^\s]+)$/i);
  if (ssh) value = `https://${ssh[1]}/${ssh[2]}`;
  try {
    const url = new URL(value);
    if (!['https:', 'http:'].includes(url.protocol)) return undefined;
    url.username = '';
    url.password = '';
    url.search = '';
    url.hash = '';
    return url.href.replace(/\/$/, '').replace(/\.git$/, '');
  } catch { return undefined; }
}

export async function exportKnowledgeBundle(options: KnowledgeExportOptions): Promise<KnowledgeExportResult> {
  const wikiDir = path.resolve(options.wikiDir);
  const bundlePath = path.join(wikiDir, KNOWLEDGE_DIRECTORY);
  let previousFiles: string[] = [];
  let previousSourceRepo: string | undefined;
  let previousSourceCommit: string | undefined;
  if (lstatIfPresent(bundlePath)) {
    if (fs.lstatSync(bundlePath).isSymbolicLink() || !fs.lstatSync(bundlePath).isDirectory()) {
      throw new Error(`Cannot export knowledge into ${bundlePath}: expected a regular directory.`);
    }
    const markerPath = path.join(bundlePath, MARKER);
    if (!lstatIfPresent(markerPath)?.isFile()) {
      throw new Error(`The knowledge directory already exists and is not managed by SemanticWiki: ${bundlePath}. Move it or choose another wiki output directory.`);
    }
    let ownership: { producer?: string; files?: unknown };
    try { ownership = JSON.parse(fs.readFileSync(markerPath, 'utf8')); } catch {
      throw new Error(`Invalid SemanticWiki ownership marker: ${markerPath}`);
    }
    if (ownership.producer !== 'semanticwiki' || !Array.isArray(ownership.files) || !ownership.files.every(safeRelativePath)) {
      throw new Error(`Invalid SemanticWiki ownership marker: ${markerPath}`);
    }
    previousFiles = ownership.files;
    // A model-free refresh need not know where the original checkout lives.
    // Keep its recorded identity, but never read an unmanaged/symlink manifest.
    const previousManifestPath = path.join(bundlePath, 'manifest.json');
    if (options.repoPath === undefined && options.sourceRepo === undefined && options.sourceCommit === undefined &&
        previousFiles.includes('manifest.json') && lstatIfPresent(previousManifestPath)?.isFile()) {
      try {
        const previous = JSON.parse(fs.readFileSync(previousManifestPath, 'utf8'));
        if (previous.format === 'semanticwiki-knowledge') {
          previousSourceRepo = typeof previous.sourceRepository === 'string' ? publicRepositoryUrl(previous.sourceRepository) : undefined;
          previousSourceCommit = typeof previous.sourceCommit === 'string' && /^[a-f\d]{4,64}$/i.test(previous.sourceCommit) ? previous.sourceCommit : undefined;
        }
      } catch { /* A damaged optional catalog must not block rebuilding the bundle. */ }
    }
  }

  const pages = loadWikiCatalog(wikiDir);
  if (!pages.length) throw new Error(`No Markdown wiki pages found in ${wikiDir}. Generate documentation first.`);
  const title = options.title || pages.find(page => /^(README|index)\.md$/.test(page.path))?.title || path.basename(wikiDir);
  let sourceRepo = publicRepositoryUrl(options.sourceRepo) || previousSourceRepo;
  let sourceCommit = options.sourceCommit || previousSourceCommit;
  if (options.repoPath && fs.existsSync(options.repoPath)) {
    const git = simpleGit(options.repoPath);
    const [commit, remote] = await Promise.allSettled([
      sourceCommit ? Promise.resolve(sourceCommit) : git.revparse(['HEAD']),
      sourceRepo ? Promise.resolve(sourceRepo) : git.getConfig('remote.origin.url').then(result => result.value || ''),
    ]);
    if (!sourceCommit && commit.status === 'fulfilled' && /^[a-f\d]{40,64}$/i.test(commit.value.trim())) sourceCommit = commit.value.trim();
    if (!sourceRepo && remote.status === 'fulfilled') sourceRepo = publicRepositoryUrl(remote.value);
  }
  const paths = new Set(pages.map(page => page.path));
  const exportedPaths = new Map(pages.map(page => [page.path, `concepts/${page.path.slice(0, -3)}.concept.md`]));
  const files = new Map<string, string | Buffer>();
  const sourceDigests = new Map(pages.map(page => [page.path, createHash('sha256').update(page.raw).digest('hex')]));

  const repositoryLink = (absolutePath: string, suffix: string): string | undefined => {
    if (!sourceRepo || !options.repoPath) return undefined;
    const relative = path.relative(path.resolve(options.repoPath), absolutePath).replace(/\\/g, '/');
    return safeRelativePath(relative)
      ? `${sourceRepo}/blob/${encodeURIComponent(sourceCommit || 'HEAD')}/${encodePath(relative)}${suffix}`
      : undefined;
  };

  const rewrite = (page: WikiDocument, href: string): string => {
    // Writer citations can contain absolute checkout paths. Resolve those before
    // interpreting leading slashes as wiki-root links (including source README.md).
    const rawPath = href.split(/[?#]/, 1)[0];
    let decoded: string;
    try { decoded = decodeURIComponent(rawPath); } catch { return href; }
    const suffix = href.match(/[?#].*$/)?.[0] || '';
    if (path.isAbsolute(decoded)) {
      const sourceLink = repositoryLink(decoded, suffix);
      if (sourceLink) return sourceLink;
    }
    const target = resolveWikiLink(page.path, href, paths);
    if (target) {
      const suffix = href.match(/[?#].*$/)?.[0] || '';
      const relative = path.posix.relative(path.posix.dirname(exportedPaths.get(page.path)!), exportedPaths.get(target)!);
      return encodePath(relative) + suffix;
    }
    if (/^[a-z][a-z\d+.-]*:/i.test(href) || href.startsWith('//') || href.startsWith('#')) return href;
    if (!decoded || decoded.includes('\\') || decoded.includes('\0')) return href;
    const sourcePath = decoded.startsWith('/')
      ? path.join(wikiDir, decoded.slice(1))
      : path.resolve(wikiDir, path.posix.dirname(page.path), decoded);
    const wikiRelative = path.relative(wikiDir, sourcePath).replace(/\\/g, '/');
    if (safeRelativePath(wikiRelative) && /\.(png|jpe?g|gif|webp|svg|pdf)$/i.test(wikiRelative) && fs.existsSync(sourcePath)) {
      const real = fs.realpathSync(sourcePath);
      if (!path.relative(fs.realpathSync(wikiDir), real).startsWith('..') && fs.statSync(real).isFile()) {
        const assetPath = `assets/${wikiRelative}`;
        files.set(assetPath, fs.readFileSync(real));
        return encodePath(path.posix.relative(path.posix.dirname(exportedPaths.get(page.path)!), assetPath)) + suffix;
      }
    }
    const sourceLink = repositoryLink(sourcePath, suffix);
    if (sourceLink) return sourceLink;
    // Unresolved links remain visible; OKF expressly permits incomplete knowledge.
    return href;
  };

  const manifestPages = pages.map(page => {
    const outputPath = exportedPaths.get(page.path)!;
    const metadata: Record<string, any> = {
      ...page.metadata,
      type: page.type,
      title: page.title,
      ...(page.description ? { description: page.description } : {}),
      semanticwiki: {
        ...(page.metadata.semanticwiki && typeof page.metadata.semanticwiki === 'object' ? page.metadata.semanticwiki : {}),
        original_path: page.path,
        content_sha256: sourceDigests.get(page.path),
      },
    };
    if (metadata.generated && (typeof metadata.generated !== 'object' || metadata.generated instanceof Date || typeof metadata.generated.by !== 'string')) {
      metadata.semanticwiki.legacy_generated = metadata.generated;
      delete metadata.generated;
    }
    const sourceResource = (resource: string): string => {
      if (sourceRepo && options.repoPath && !/^[a-z][a-z\d+.-]*:/i.test(resource)) {
        const match = resource.match(/^(.*?)(?::(\d+)(?:-(\d+))?)?$/);
        const sourceFile = match?.[1] || resource;
        const lines = match?.[2] ? `#L${match[2]}${match[3] ? `-L${match[3]}` : ''}` : '';
        if (path.isAbsolute(sourceFile)) {
          const sourceLink = repositoryLink(sourceFile, lines);
          if (sourceLink) return sourceLink;
        }
        if (safeRelativePath(sourceFile) && fs.existsSync(path.join(options.repoPath, sourceFile))) {
          return `${sourceRepo}/blob/${encodeURIComponent(sourceCommit || 'HEAD')}/${encodePath(sourceFile)}${lines}`;
        }
      }
      return rewrite(page, resource);
    };
    // Legacy generators used source strings. OKF source entries require resource.
    if (Array.isArray(metadata.sources)) {
      metadata.sources = metadata.sources.flatMap((source: unknown) => {
        if (typeof source === 'string' && source.trim()) return [{ resource: sourceResource(source) }];
        if (source && typeof source === 'object' && 'resource' in source && typeof source.resource === 'string') {
          return [{ ...source, resource: sourceResource(source.resource) }];
        }
        return [];
      });
    }
    if (typeof metadata.resource === 'string') metadata.resource = rewrite(page, metadata.resource);
    const exportedContent = matter.stringify(rewriteMarkdownLinks(page.content, href => rewrite(page, href)), metadata);
    files.set(outputPath, exportedContent);
    const related = [...new Set(page.links.flatMap(link => link.path ? [exportedPaths.get(link.path)!] : []))];
    return {
      ...documentSummary(page), id: outputPath.slice(0, -3), path: outputPath,
      headings: extractHeadings(matter(exportedContent).content),
      originalPath: page.path, contentSha256: sourceDigests.get(page.path), related,
      sources: metadata.sources || [], generated: metadata.generated, verified: metadata.verified,
    };
  });

  const directories = new Set<string>(['', 'concepts']);
  for (const page of manifestPages) {
    let dir = path.posix.dirname(page.path);
    while (dir !== '.') {
      directories.add(dir);
      dir = path.posix.dirname(dir);
    }
  }
  for (const directory of [...directories].sort()) {
    const heading = directory ? path.posix.basename(directory) : title;
    let index = `${directory ? '' : `---\nokf_version: "${OKF_VERSION}"\n---\n\n`}# ${markdownLabel(heading)}\n\n`;
    if (!directory) index += 'Source-grounded codebase documentation. Read a directory index first, then only the concepts relevant to your task. Follow source references back to the code before making changes.\n\n';
    const childDirectories = [...directories].filter(dir => dir && path.posix.dirname(dir) === (directory || '.')).sort();
    for (const child of childDirectories) {
      const count = manifestPages.filter(page => page.path.startsWith(`${child}/`)).length;
      index += `- [${markdownLabel(path.posix.basename(child))}](${encodePath(path.posix.relative(directory || '.', child))}/index.md) — ${count} documented concepts\n`;
    }
    for (const page of manifestPages.filter(page => path.posix.dirname(page.path) === directory)) {
      index += `- [${markdownLabel(page.title)}](${encodePath(path.posix.basename(page.path))})${page.description ? ` — ${page.description}` : ''}\n`;
    }
    if (!directory) index += '\n## For coding agents\n\n- [Machine-readable catalog](manifest.json) — IDs, descriptions, headings, links, source references, and content hashes.\n- This export does not verify model-generated claims. Trust is derived only from existing OKF `verified` metadata.\n- Use `semanticwiki mcp-server -o /absolute/path/to/wiki` for search, paginated page reads, and related concepts.\n';
    files.set(path.posix.join(directory, 'index.md'), index);
  }

  const manifest = {
    format: 'semanticwiki-knowledge', version: 1, okfVersion: OKF_VERSION,
    title, exportedAt: new Date().toISOString(), exporter: `semanticwiki/${version}`,
    ...(sourceRepo ? { sourceRepository: sourceRepo } : {}),
    ...(sourceCommit ? { sourceCommit } : {}),
    entrypoint: 'index.md', pageCount: pages.length, pages: manifestPages,
  };
  files.set('manifest.json', JSON.stringify(manifest, null, 2) + '\n');

  // Validate every destination before modifying a previous export. User additions survive.
  for (const relative of [...previousFiles, ...files.keys()]) {
    assertRegularDestination(bundlePath, relative);
    if (files.has(relative) && fs.existsSync(path.join(bundlePath, relative)) && !previousFiles.includes(relative)) {
      throw new Error(`A user file conflicts with the generated knowledge bundle: ${path.join(bundlePath, relative)}`);
    }
  }
  fs.mkdirSync(bundlePath, { recursive: true });
  for (const [relative, content] of files) {
    const destination = path.join(bundlePath, relative);
    fs.mkdirSync(path.dirname(destination), { recursive: true });
    fs.writeFileSync(destination, content);
  }
  for (const relative of previousFiles) {
    const stalePath = path.join(bundlePath, relative);
    if (!files.has(relative) && fs.existsSync(stalePath) && fs.lstatSync(stalePath).isFile()) fs.unlinkSync(stalePath);
  }
  fs.writeFileSync(path.join(bundlePath, MARKER), JSON.stringify({ producer: 'semanticwiki', files: [...files.keys()].sort() }, null, 2) + '\n');

  const discoveryPath = path.join(wikiDir, 'llms.txt');
  const discoveryStat = lstatIfPresent(discoveryPath);
  const discoveryWritten = !discoveryStat || (discoveryStat.isFile() && fs.readFileSync(discoveryPath, 'utf8').includes(DISCOVERY_MARKER));
  if (discoveryWritten) {
    const discovery = `${DISCOVERY_MARKER}\n# ${markdownLabel(title)}\n\n> Architectural documentation with source references, exported as Open Knowledge Format ${OKF_VERSION}.\n\n## Start here\n\n- [Knowledge index](knowledge/index.md): Progressive navigation through the codebase.\n- [Knowledge catalog](knowledge/manifest.json): Machine-readable page IDs, sections, relationships, provenance, and hashes.\n\n## Use with an agent\n\nRead the index, search for relevant concepts, then read specific sections. Check source code before making changes; generated documentation may be incomplete or stale.\n\nFor local search and bounded reads, configure an MCP server with command \`semanticwiki\` and arguments \`["mcp-server", "-o", "/absolute/path/to/wiki"]\`. Start with \`get_knowledge_manifest\`, then \`search_wiki\` and \`get_wiki_page\`.\n`;
    fs.writeFileSync(discoveryPath, discovery);
  }
  return { bundlePath, pageCount: pages.length, manifestPath: path.join(bundlePath, 'manifest.json'), discoveryWritten };
}
